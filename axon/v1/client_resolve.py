"""Read-only, evidence-backed proposals for missed SDK declarations.

Files are treated as data. Ambiguous ownership and spec identities are exposed
for review; the resolver never executes build files or guesses a target.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any, Literal

import yaml  # type: ignore[import-untyped]
from pydantic import BaseModel, Field

from axon.v1.client_discovery import _packages
from axon.v1.servicemap import ClientDecl, is_ignored, load_service_map, owner_of


class ClientEvidence(BaseModel):
    file: str
    line: int
    field: str
    value: Any


class ClientProposal(BaseModel):
    client: ClientDecl | None = None
    service: str = ""
    status: Literal["ready", "ambiguous", "conflict"] = "ambiguous"
    evidence: list[ClientEvidence] = Field(default_factory=list)
    candidates: dict[str, list[str]] = Field(default_factory=dict)
    conflicts: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)

    @property
    def ambiguous(self) -> bool:
        return self.status == "ambiguous"


def normalize_name(name: str) -> set[str]:
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", name)
    return set(re.findall(r"[a-z0-9]+", words.lower())) - {"client", "api", "sdk"}


_BANNER = re.compile(
    r"Generated by Swagger Codegen|OpenAPI[ -]Generator|@(?:javax|jakarta)\.annotation\.Generated",
    re.I,
)
_IMPORT = re.compile(r"(?:from|import)\s+([\w.]+)")
_FACTORY = re.compile(r"(?:[A-Za-z_]\w*\.)*(?:GET_[A-Z_]+_API|get_[A-Za-z]+Api)(?=\s*\()")


def resolve_client(root: Path, name: str, service: str = "", target: str = "") -> ClientProposal:
    """Collect a deterministic proposal without modifying config or caches.

    Source imports are read fresh so a stale facts cache cannot hide consumers.
    Target inference accepts a unique operationId superset with >=80% overlap;
    counts are retained as evidence, and ties remain ambiguous.
    """
    root = Path(root).resolve()
    sm = load_service_map(root)
    result = ClientProposal()
    target_repo = ""
    if "::" in target:
        target_repo, target = target.split("::", 1)
        if not target_repo or not target:
            result.conflicts.append("cross-repo target requires repo::service")
        result.warnings.append("Explicit cross-repo target is not verified by this local checkout")
    services = {s.id for s in sm.services}
    for label, value in (("service", service), ("target_service", target)):
        if value and value not in services and not (label == "target_service" and target_repo):
            result.conflicts.append(f"unknown {label}: {value}")
    tokens = normalize_name(name)
    if not tokens:
        result.conflicts.append("client name has no identifying tokens")
    packages: set[str] = set()
    paths: set[str] = set()
    factories: set[str] = set()
    owners: set[str] = set()
    consumers: set[str] = set()
    specs: dict[str, tuple[dict[str, Any], set[str]]] = {}
    texts: dict[str, str] = {}

    def matches(value: str) -> bool:
        return bool(tokens) and tokens <= normalize_name(value)

    def evidence(rel: str, line: int, field: str, value: Any) -> None:
        result.evidence.append(ClientEvidence(file=rel, line=line, field=field, value=value))

    # Prune ignored directories before descending, including virtualenvs.
    for directory, dirs, files in os.walk(root, followlinks=False):
        base = Path(directory)
        dirs[:] = sorted(
            d for d in dirs if not is_ignored(sm, (base / d).relative_to(root).as_posix())
        )
        for filename in sorted(files):
            path = base / filename
            rel = path.relative_to(root).as_posix()
            if path.is_symlink() or is_ignored(sm, rel):
                continue
            if path.suffix not in {
                ".py",
                ".java",
                ".go",
                ".ts",
                ".js",
                ".yaml",
                ".yml",
                ".json",
                ".cfg",
                ".txt",
                ".toml",
                ".xml",
                ".mod",
            } and filename not in {"BUILD", "BUILD.bazel"}:
                continue
            try:
                if path.stat().st_size > 2_000_000:
                    continue
                texts[rel] = path.read_text(encoding="utf-8")
            except (OSError, UnicodeError):
                continue
    for rel, text in texts.items():
        filename = Path(rel).name
        kind, sid = owner_of(sm, rel)
        if filename in {"swagger.cfg", "BUILD", "BUILD.bazel"}:
            for package in sorted(_packages(filename, text)):
                if matches(package) or matches(rel):
                    packages.add(package)
                    line = next(
                        (i for i, row in enumerate(text.splitlines(), 1) if package in row), 1
                    )
                    evidence(rel, line, "packages", package)
                    if kind == "service":
                        owners.add(sid)
        for line, row in enumerate(text.splitlines(), 1):
            if Path(rel).suffix in {".py", ".java", ".go", ".ts", ".js"}:
                for match in _IMPORT.finditer(row):
                    package = match.group(1)
                    if matches(package):
                        # Python from-imports identify the package before the imported symbol.
                        packages.add(package)
                        evidence(rel, line, "packages", package)
                        if kind == "service":
                            consumers.add(sid)
                            evidence(rel, line, "service", sid)
                for match in _FACTORY.finditer(row):
                    factory = match.group(0)
                    if matches(factory):
                        factories.add(factory)
                        evidence(rel, line, "factories", factory)
                        if kind == "service":
                            consumers.add(sid)
                if _BANNER.search(row) and matches(rel):
                    parent = Path(rel).parent
                    # Prefer the named SDK directory over its nested api/models.
                    named = [p for p in parent.parents if p != Path(".") and matches(p.name)]
                    if matches(parent.name):
                        named.insert(0, parent)
                    folder_path = named[0] if named else parent
                    folder = folder_path.as_posix()
                    if Path(rel).suffix == ".py" and re.fullmatch(
                        r"[A-Za-z_]\w*", folder_path.name
                    ):
                        packages.add(folder_path.name)
                        evidence(rel, line, "packages", folder_path.name)
                    paths.add(folder)
                    evidence(rel, line, "paths", folder)
                    if kind == "service":
                        owners.add(sid)
            dependency = (
                filename.startswith("requirements") and filename.endswith(".txt")
            ) or filename in {"pyproject.toml", "pom.xml", "go.mod"}
            if dependency:
                for match in re.finditer(r"[A-Za-z][A-Za-z0-9_.-]*(?:/[A-Za-z0-9_.-]+)*", row):
                    value = match.group(0)
                    if matches(value):
                        package = value.replace("-", "_")
                        packages.add(package)
                        evidence(rel, line, "packages", package)
        if Path(rel).suffix in {".json", ".yaml", ".yml"} and not filename.startswith("axon"):
            try:
                data = yaml.safe_load(text)
            except yaml.YAMLError:
                continue
            if (
                isinstance(data, dict)
                and ("openapi" in data or "swagger" in data)
                and isinstance(data.get("paths"), dict)
                and isinstance(data.get("info", {}), dict)
            ):
                ops = {
                    str(op["operationId"])
                    for methods in data.get("paths", {}).values()
                    if isinstance(methods, dict)
                    for op in methods.values()
                    if isinstance(op, dict) and op.get("operationId")
                }
                specs[rel] = (data, ops)
    # A generated package root is stronger than a nested api/ directory.
    paths = {p for p in paths if not any(p.startswith(q + "/") for q in paths if q != p)}
    declared_specs = {p for s in sm.services for p in s.specs}
    copies = sorted(
        p
        for p, (data, _) in specs.items()
        if p not in declared_specs
        and (matches(p) or matches(str(data.get("info", {}).get("title", ""))))
    )
    spec = copies[0] if len(copies) == 1 else ""
    if len(copies) > 1:
        result.candidates["spec"] = copies
    targets: set[str] = set()
    if spec:
        evidence(spec, 1, "spec", spec)
        wanted = specs[spec][1]
        if wanted:
            for svc in sm.services:
                known = set().union(*(specs[p][1] for p in svc.specs if p in specs))
                overlap = len(wanted & known)
                if overlap and overlap / len(wanted) >= 0.8:
                    targets.add(svc.id)
                    evidence(
                        spec, 1, "target_service", f"{svc.id}: {overlap}/{len(wanted)} operationIds"
                    )
    base_urls: set[str] = set()
    if spec:
        spec_data = specs[spec][0]
        urls = [str(s.get("url", "")) for s in spec_data.get("servers", []) if isinstance(s, dict)]
        if spec_data.get("host"):
            schemes = spec_data.get("schemes") or ["https"]
            urls.extend(
                f"{scheme}://{spec_data['host']}{spec_data.get('basePath', '')}"
                for scheme in schemes
            )
        for url in urls:
            if not url:
                continue
            base_urls.add(url)
            for line, text in enumerate(texts[spec].splitlines(), 1):
                if url in text or str(spec_data.get("host", "\x00")) in text:
                    evidence(spec, line, "base_urls", url)
                    break
    for rel, text in texts.items():
        for line, content in enumerate(text.splitlines(), 1):
            if not any(re.search(r"\b" + re.escape(p) + r"\.", content) for p in packages):
                continue
            for variable in re.findall(r"os\.environ\[\s*[\"\x27]([^\"\x27]+)", content):
                value = f"env:{variable}"
                base_urls.add(value)
                evidence(rel, line, "base_urls", value)
    base_targets = {s.id for s in sm.services if set(s.base_urls) & base_urls}
    if base_targets:
        targets = (targets & base_targets) if targets else base_targets
    if not target and len(targets) > 1:
        result.candidates["target_service"] = sorted(targets)
    chosen = owners or consumers
    if not service and len(chosen) != 1:
        result.candidates["service"] = sorted(chosen)
    result.service = service or (next(iter(chosen)) if len(chosen) == 1 else "")
    cid = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    result.client = ClientDecl(
        id=cid,
        packages=sorted(packages),
        paths=sorted(paths),
        factories=sorted(factories),
        base_urls=sorted(base_urls),
        spec=spec,
        target_service=target or (next(iter(targets)) if len(targets) == 1 else ""),
        target_repo=target_repo,
    )
    for svc in sm.services:
        for existing in svc.clients:
            claimed = sorted(
                p
                for p in packages
                if any(
                    p == q or p.startswith(q + ".") or q.startswith(p + ".")
                    for q in existing.packages
                )
            )
            if claimed or existing.id == cid:
                result.conflicts.append(
                    f"client patch {existing.id} --add-package: "
                    f"existing client claims {', '.join(claimed) or cid}"
                )
    for link in sm.links:
        if any(link.call_name.startswith(p + ".") for p in packages):
            result.warnings.append(
                f"review potentially redundant top-level link: {link.id or link.call_name}"
            )
    if not packages and not factories:
        result.candidates.setdefault("packages", [])
        result.warnings.append(
            "No static package or factory evidence; dynamic imports remain unknown."
        )
    if not result.client.target_service:
        result.warnings.append(
            "Target unknown: no unique spec operation identity; "
            "no target was inferred from the name."
        )
    result.status = (
        "conflict" if result.conflicts else "ambiguous" if result.candidates else "ready"
    )
    return result
