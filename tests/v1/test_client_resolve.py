def test_generated_paths_and_dependency_evidence(tmp_path):
    (tmp_path / "axon.yaml").write_text("services: [{id: a, roots: [a]}]\n")
    folder = tmp_path / "a/payments_client"
    folder.mkdir(parents=True)
    (folder / "api_client.py").write_text("# Generated by Swagger Codegen\n")
    (tmp_path / "requirements.txt").write_text("payments-client==1.0\n")
    result = resolve_client(tmp_path, "payments")
    assert result.client.paths == ["a/payments_client"]
    assert result.client.packages == ["payments_client"]
    assert {e.file for e in result.evidence} >= {
        "requirements.txt",
        "a/payments_client/api_client.py",
    }


def test_spec_identity_and_ambiguous_target(tmp_path):
    (tmp_path / "axon.yaml").write_text(
        "services: [{id: a, roots: [a]}, {id: b, specs: [b.yaml]}]\n"
    )
    (tmp_path / "a").mkdir()
    (tmp_path / "a/use.py").write_text("import payments_client\n")
    spec = (
        "openapi: 3.0.0\ninfo: {title: Payments API}\n"
        "paths:\n  /pay:\n    post: {operationId: charge}\n"
    )
    (tmp_path / "payments.yaml").write_text(spec)
    (tmp_path / "b.yaml").write_text(spec)
    result = resolve_client(tmp_path, "payments")
    assert result.client.spec == "payments.yaml"
    assert result.client.target_service == "b"
    assert any(e.field == "target_service" and "1/1" in e.value for e in result.evidence)
    (tmp_path / "axon.yaml").write_text(
        "services: [{id: a, roots: [a], specs: [b.yaml]}, {id: b, specs: [b.yaml]}]\n"
    )
    result = resolve_client(tmp_path, "payments")
    assert result.status == "ambiguous"
    assert result.candidates["target_service"] == ["a", "b"]
    assert resolve_client(tmp_path, "payments", target="b").status == "ready"


def test_build_metadata_is_never_executed_and_ignored_files_are_skipped(tmp_path):
    (tmp_path / "axon.yaml").write_text("services: [{id: a, roots: [a]}]\n")
    (tmp_path / "a").mkdir()
    (tmp_path / "a/BUILD").write_text(
        "raise RuntimeError('must not execute')\nswagger_client(packageName='payments_client')\n"
    )
    (tmp_path / ".venv").mkdir()
    (tmp_path / ".venv/ignored.py").write_text("import payments_fake\n")
    result = resolve_client(tmp_path, "payments")
    assert result.client.packages == ["payments_client"]
    assert not any(e.file.startswith(".venv/") for e in result.evidence)


def test_spec_server_url_can_identify_target(tmp_path):
    (tmp_path / "axon.yaml").write_text(
        "services: [{id: a, roots: [a]}, {id: b, base_urls: ['https://pay.example/v1']}]\n"
    )
    (tmp_path / "a").mkdir()
    (tmp_path / "a/use.py").write_text("import payments_client\n")
    (tmp_path / "payments.yaml").write_text(
        "openapi: 3.0.0\ninfo: {title: Payments API}\npaths: {}\n"
        "servers:\n- url: https://pay.example/v1\n"
    )
    result = resolve_client(tmp_path, "payments")
    assert result.client.target_service == "b"
    assert result.client.base_urls == ["https://pay.example/v1"]
    assert any(e.field == "base_urls" and e.line == 5 for e in result.evidence)


def test_evidenced_environment_argument_breaks_operation_tie(tmp_path):
    (tmp_path / "axon.yaml").write_text(
        "services:\n- {id: a, roots: [a], specs: [a.yaml]}\n"
        "- {id: b, specs: [b.yaml], base_urls: ['env:PAYMENTS_URL']}\n"
    )
    (tmp_path / "a").mkdir()
    (tmp_path / "a/use.py").write_text(
        "import os\nimport payments_client\n"
        'api = payments_client.ApiClient(host=os.environ["PAYMENTS_URL"])\n'
    )
    spec = (
        "openapi: 3.0.0\ninfo: {title: Payments API}\n"
        "paths: { /pay: {post: {operationId: charge}}}\n"
    )
    for name in ("payments.yaml", "a.yaml", "b.yaml"):
        (tmp_path / name).write_text(spec)
    result = resolve_client(tmp_path, "payments")
    assert result.status == "ready"
    assert result.client.target_service == "b"
    assert result.client.base_urls == ["env:PAYMENTS_URL"]
    assert any(
        e.file == "a/use.py" and e.line == 3 and e.field == "base_urls" for e in result.evidence
    )


def test_ambiguous_environment_mapping_and_unrelated_env_is_ignored(tmp_path):
    (tmp_path / "axon.yaml").write_text(
        "services: [{id: a, roots: [a], base_urls: ['env:SHARED']}, "
        "{id: b, base_urls: ['env:SHARED']}]\n"
    )
    (tmp_path / "a").mkdir()
    (tmp_path / "a/use.py").write_text(
        "import os\nimport payments_client\n"
        'api = payments_client.ApiClient(host=os.environ["SHARED"])\n'
        'unrelated = os.environ["PAYMENTS_OTHER"]\n'
    )
    result = resolve_client(tmp_path, "payments")
    assert result.status == "ambiguous"
    assert result.candidates["target_service"] == ["a", "b"]
    assert result.client.base_urls == ["env:SHARED"]


def test_explicit_cross_repo_target(tmp_path):
    (tmp_path / "axon.yaml").write_text("repo: local\nservices: [{id: a, roots: [a]}]\n")
    (tmp_path / "a").mkdir()
    (tmp_path / "a/use.py").write_text("import payments_client\n")
    result = resolve_client(tmp_path, "payments", target="remote::payments")
    assert result.status == "ready"
    assert result.client.target_service == "payments"
    assert result.client.target_repo == "remote"
    assert any("cross-repo" in warning for warning in result.warnings)
