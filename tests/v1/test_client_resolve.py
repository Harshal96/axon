from axon.v1.client_resolve import normalize_name, resolve_client


def test_names():
    for name in ("PaymentsApi", "payments-client", "payments_client"):
        assert normalize_name(name) == {"payments"}


def test_metadata(tmp_path):
    (tmp_path / "axon.yaml").write_text("services: [{id: shop, roots: [shop]}]\n")
    (tmp_path / "shop").mkdir()
    (tmp_path / "shop/swagger.cfg").write_text("packageName: payments_client\n")
    result = resolve_client(tmp_path, "PaymentsApi")
    assert result.status == "ready"
    assert result.service == "shop"
    assert result.client.packages == ["payments_client"]
    assert result.client.target_service == ""
    assert all(e.line >= 1 for e in result.evidence)


def test_ambiguous_consumers(tmp_path):
    (tmp_path / "axon.yaml").write_text("services: [{id: a, roots: [a]}, {id: b, roots: [b]}]\n")
    for folder in ("a", "b"):
        (tmp_path / folder).mkdir()
        (tmp_path / folder / "use.py").write_text("import payments_client\n")
    result = resolve_client(tmp_path, "payments")
    assert result.status == "ambiguous"
    assert result.candidates["service"] == ["a", "b"]
    assert resolve_client(tmp_path, "payments", service="a").status == "ready"


def test_factory(tmp_path):
    (tmp_path / "axon.yaml").write_text("services: [{id: a, roots: [a]}]\n")
    (tmp_path / "a").mkdir()
    (tmp_path / "a/use.py").write_text("api = settings.GET_PAYMENTS_API()\n")
    result = resolve_client(tmp_path, "payments")
    assert result.client.factories == ["settings.GET_PAYMENTS_API"]
    assert result.service == "a"


def test_conflict(tmp_path):
    (tmp_path / "axon.yaml").write_text(
        "services: [{id: a, roots: [a], clients: [{id: old, packages: [payments_client]}]}]\n"
    )
    (tmp_path / "a").mkdir()
    (tmp_path / "a/use.py").write_text("import payments_client\n")
    result = resolve_client(tmp_path, "payments")
